import React, { useState } from 'react';
import { Binary, Copy, Check, Info } from 'lucide-react';
import { TACInstructionItem } from '../types/compiler';

interface RawTACViewerProps {
  instructions?: TACInstructionItem[] | null;
  rawText?: string | null;
}

export const RawTACViewer: React.FC<RawTACViewerProps> = ({
  instructions,
  rawText,
}) => {
  const [copied, setCopied] = useState(false);

  if (!instructions || instructions.length === 0) {
    return (
      <div className="h-full flex flex-col items-center justify-center text-studio-400 p-6">
        <Binary className="w-8 h-8 text-studio-600 mb-2" />
        <p className="text-sm font-medium">No Intermediate Code Available</p>
        <p className="text-xs text-studio-500 mt-1">Compile code to inspect generated Three-Address Code quadruples.</p>
      </div>
    );
  }

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(rawText || '');
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Ignore
    }
  };

  return (
    <div className="h-full flex flex-col bg-studio-900">
      {/* Header Bar */}
      <div className="p-3 border-b border-studio-700 flex items-center justify-between gap-2 bg-studio-850 select-none">
        <div className="flex items-center gap-2">
          <span className="text-xs font-semibold text-studio-200">Raw Three-Address Code (Unoptimized IR)</span>
          <span className="text-xs font-mono text-studio-400 bg-studio-800 px-2 py-0.5 rounded border border-studio-700">
            {instructions.length} Quadruples
          </span>
        </div>

        <button
          onClick={handleCopy}
          className="flex items-center gap-1.5 px-2.5 py-1 text-xs text-studio-300 hover:text-white bg-studio-800 hover:bg-studio-750 rounded border border-studio-700 transition-colors"
        >
          {copied ? <Check className="w-3 h-3 text-accent-green" /> : <Copy className="w-3 h-3" />}
          <span>Copy TAC</span>
        </button>
      </div>

      {/* Explanatory Banner */}
      <div className="px-4 py-2.5 bg-studio-850/60 border-b border-studio-800 text-[11px] text-studio-400 flex items-center gap-2">
        <Info className="w-3.5 h-3.5 text-accent-blue shrink-0" />
        <span>Generated by <code className="text-accent-blue">TACGenerator</code> directly from the AST prior to optimization passes.</span>
      </div>

      {/* Instructions Stream */}
      <div className="flex-1 overflow-auto p-4 font-mono text-xs text-studio-300 select-text leading-relaxed">
        <div className="space-y-1 max-w-2xl">
          {instructions.map((inst) => {
            const isLabel = inst.op === 'LABEL';
            const isJump = inst.op === 'JUMP' || inst.op === 'JUMP_IF_FALSE';
            const isPrint = inst.op === 'PRINT';

            return (
              <div
                key={inst.index}
                className={`flex items-baseline gap-4 py-0.5 px-2 rounded hover:bg-studio-800/60 transition-colors ${
                  isLabel ? 'font-semibold text-accent-yellow' : ''
                }`}
              >
                {/* Index */}
                <span className="w-8 text-right text-studio-500 text-[11px] select-none font-mono">
                  {inst.index}:
                </span>

                {/* Instruction Text */}
                <div className="flex-1">
                  {isLabel ? (
                    <span className="text-accent-yellow">{inst.result}:</span>
                  ) : isJump ? (
                    <span className="text-accent-purple">{inst.text}</span>
                  ) : isPrint ? (
                    <span className="text-accent-blue">{inst.text}</span>
                  ) : (
                    <span className="text-studio-200">{inst.text}</span>
                  )}
                </div>

                {/* Opcode tag */}
                <span className="text-[10px] text-studio-500 uppercase px-1.5 py-0.2 rounded bg-studio-800 border border-studio-750 select-none">
                  {inst.op}
                </span>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
};
